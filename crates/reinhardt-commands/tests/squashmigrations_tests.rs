#[tokio::test]
async fn validation_errors_happen_before_prompting_and_preserve_existing_files() {
	// Arrange
	let (_temporary, root) = create_migration_tree();
	let existing = root.join("polls/0001_initial.rs");
	let existing_source = fs::read_to_string(&existing).unwrap();
	let mut options = default_options();
	options.migration_name = "000".to_string();
	let mut confirmation = TestConfirmation::terminal("yes\n");
	let mut stdout = Vec::new();
	let mut stderr = Vec::new();

	// Act
	let error = execute_squashmigrations_with_io(
		&root,
		options,
		&mut confirmation,
		&mut stdout,
		&mut stderr,
	)
	.await
	.unwrap_err();

	// Assert
	assert_eq!(
		error.to_string(),
		"Execution error: Invalid migration: Ambiguous migration prefix '000' for app 'polls'; \
		 candidates: 0001_initial, 0002_remove_entries"
	);
	assert_eq!(confirmation.read_count, 0);
	assert_eq!(fs::read_to_string(existing).unwrap(), existing_source);
	assert!(!root.join("polls/0001_squashed_0002.rs").exists());
}

