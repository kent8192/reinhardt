#![cfg(feature = "migrations")]

use reinhardt_commands::{
	ConfirmationReader, SquashMigrationsOptions, execute_squashmigrations_with_io,
};
use reinhardt_db::migrations::{
	ColumnDefinition, FieldType, FilesystemRepository, FilesystemSource, Migration,
	MigrationRenderOptions, MigrationSource, Operation,
};
use std::fs;
use std::io;
use tempfile::TempDir;

struct TestConfirmation {
	terminal: bool,
	answer: &'static str,
	read_count: usize,
}

impl TestConfirmation {
	fn terminal(answer: &'static str) -> Self {
		Self {
			terminal: true,
			answer,
			read_count: 0,
		}
	}

	fn non_terminal() -> Self {
		Self {
			terminal: false,
			answer: "",
			read_count: 0,
		}
	}
}

impl ConfirmationReader for TestConfirmation {
	fn is_terminal(&self) -> bool {
		self.terminal
	}

	fn read_line(&mut self, buffer: &mut String) -> io::Result<usize> {
		self.read_count += 1;
		buffer.push_str(self.answer);
		Ok(self.answer.len())
	}
}

fn create_migration_tree() -> (TempDir, std::path::PathBuf) {
	let temporary = TempDir::new().unwrap();
	let root = temporary.path().join("migrations");
	let repository = FilesystemRepository::new(&root);

	let mut first = Migration::new("0001_initial", "polls");
	first.operations.push(Operation::CreateTable {
		name: "entries".to_string(),
		columns: vec![ColumnDefinition::new("id", FieldType::Integer)],
		constraints: vec![],
		without_rowid: None,
		interleave_in_parent: None,
		partition: None,
	});
	let mut second = Migration::new("0002_remove_entries", "polls");
	second.dependencies = vec![("polls".to_string(), "0001_initial".to_string())];
	second.operations.push(Operation::DropTable {
		name: "entries".to_string(),
	});

	for migration in [&first, &second] {
		let source = repository
			.render(
				migration,
				MigrationRenderOptions {
					include_header: true,
				},
			)
			.unwrap();
		repository
			.create_new_source(&migration.app_label, &migration.name, &source)
			.unwrap();
	}

	(temporary, root)
}

fn default_options() -> SquashMigrationsOptions {
	SquashMigrationsOptions {
		app_label: "polls".to_string(),
		start_migration: None,
		migration_name: "0002".to_string(),
		no_optimize: false,
		no_input: false,
		no_header: false,
		squashed_name: None,
	}
}

#[tokio::test]
async fn tty_confirmation_accepts_and_writes_the_exact_summary() {
	// Arrange
	let (_temporary, root) = create_migration_tree();
	let mut confirmation = TestConfirmation::terminal("yes\n");
	let mut stdout = Vec::new();
	let mut stderr = Vec::new();
	let expected_path = root.join("polls/0001_squashed_0002.rs");

	// Act
	let summary = execute_squashmigrations_with_io(
		&root,
		default_options(),
		&mut confirmation,
		&mut stdout,
		&mut stderr,
	)
	.await
	.unwrap()
	.unwrap();

	// Assert
	assert_eq!(summary.app_label, "polls");
	assert_eq!(summary.start_migration, "0001_initial");
	assert_eq!(summary.end_migration, "0002_remove_entries");
	assert_eq!(summary.squashed_name, "0001_squashed_0002");
	assert_eq!(summary.migration_count, 2);
	assert_eq!(summary.original_operation_count, 2);
	assert_eq!(summary.optimized_operation_count, 0);
	assert_eq!(summary.path, expected_path);
	assert_eq!(confirmation.read_count, 1);
	assert_eq!(
		String::from_utf8(stderr).unwrap(),
		"Squash 2 migrations (2 operations -> 0) into \
		 0001_squashed_0002? [y/N] "
	);
	assert_eq!(
		String::from_utf8(stdout).unwrap(),
		format!(
			"App: polls\nRange: 0001_initial -> 0002_remove_entries\n\
			 Migrations: 2\nOperations: 2 -> 0\nCreated: {}\n",
			expected_path.display()
		)
	);
	assert!(
		fs::read_to_string(expected_path)
			.unwrap()
			.starts_with("// Generated by Reinhardt migrations.\n\n")
	);
}

#[tokio::test]
async fn tty_confirmation_declines_without_writing() {
	// Arrange
	let (_temporary, root) = create_migration_tree();
	let mut confirmation = TestConfirmation::terminal("n\n");
	let mut stdout = Vec::new();
	let mut stderr = Vec::new();

	// Act
	let summary = execute_squashmigrations_with_io(
		&root,
		default_options(),
		&mut confirmation,
		&mut stdout,
		&mut stderr,
	)
	.await
	.unwrap();

	// Assert
	assert_eq!(summary, None);
	assert_eq!(stdout, b"");
	assert_eq!(
		String::from_utf8(stderr).unwrap(),
		"Squash 2 migrations (2 operations -> 0) into \
		 0001_squashed_0002? [y/N] Cancelled.\n"
	);
	assert!(!root.join("polls/0001_squashed_0002.rs").exists());
}

#[tokio::test]
async fn non_terminal_input_is_rejected_without_no_input() {
	// Arrange
	let (_temporary, root) = create_migration_tree();
	let mut confirmation = TestConfirmation::non_terminal();
	let mut stdout = Vec::new();
	let mut stderr = Vec::new();

	// Act
	let error = execute_squashmigrations_with_io(
		&root,
		default_options(),
		&mut confirmation,
		&mut stdout,
		&mut stderr,
	)
	.await
	.unwrap_err();

	// Assert
	assert_eq!(
		error.to_string(),
		"Invalid arguments: squashmigrations requires terminal input; use --no-input in \
		 non-interactive environments"
	);
	assert_eq!(confirmation.read_count, 0);
	assert_eq!(stdout, b"");
	assert_eq!(stderr, b"");
	assert!(!root.join("polls/0001_squashed_0002.rs").exists());
}

