#[tokio::test]
async fn no_optimize_preserves_operation_order_and_no_header_omits_header() {
	// Arrange
	let (_temporary, root) = create_migration_tree();
	let mut options = default_options();
	options.no_input = true;
	options.no_optimize = true;
	options.no_header = true;
	options.squashed_name = Some("0001_compacted".to_string());
	let mut confirmation = TestConfirmation::non_terminal();
	let mut stdout = Vec::new();
	let mut stderr = Vec::new();

	// Act
	execute_squashmigrations_with_io(&root, options, &mut confirmation, &mut stdout, &mut stderr)
		.await
		.unwrap();

	// Assert
	let path = root.join("polls/0001_compacted.rs");
	let source = fs::read_to_string(&path).unwrap();
	let loaded = FilesystemSource::new(&root)
		.all_migrations()
		.await
		.unwrap()
		.into_iter()
		.find(|migration| migration.name == "0001_compacted")
		.unwrap();
	assert!(!source.contains("Generated by Reinhardt migrations"));
	assert_eq!(
		loaded.operations,
		vec![
			Operation::CreateTable {
				name: "entries".to_string(),
				columns: vec![ColumnDefinition::new("id", FieldType::Integer)],
				constraints: vec![],
				without_rowid: None,
				interleave_in_parent: None,
				partition: None,
			},
			Operation::DropTable {
				name: "entries".to_string(),
			},
		]
	);
}
