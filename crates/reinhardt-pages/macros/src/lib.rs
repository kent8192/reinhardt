/// Derives typed field signals and form traits for a form values struct.
/// Page component macro
///
/// Creates a `Page` directly or a reusable page factory with a closure-style DSL.
///
/// `page!({ ... })` returns a `Page` immediately and implicitly captures free
/// value identifiers from the surrounding Rust scope. Captured values are cloned
/// into generated reactive and event closures, so they must implement `Clone`.
///
/// `page!(|| { ... })` and `page!(|props: Props| { ... })` return callable
/// factories. Closure forms keep strict capture discipline: values used in the
/// body must be declared in the closure parameter list.
///
/// ## Syntax
///
/// ```text
/// // Direct Page form
/// page!({
///     element {
///         attr: "value",
///         @event: |e| { handler(e) },
///         child_element { ... }
///         "text content"
///     }
/// })
///
/// // Factory syntax
/// page!(|prop1: Type1, prop2: Type2| {
///     element {
///         attr: "value",
///         @event: |e| { handler(e) },
///         child_element { ... }
///         "text content"
///     }
/// })
///
/// // With head directive (for SSR)
/// page! {
///     #head: my_head,
///     {
///         element { ... }
///     }
/// }
/// ```
///
/// ## Body Forms
///
/// Choose direct pages for app screens and ordinary functions that return
/// `Page`. Choose closure forms for factories that are called later:
///
/// | Pattern | Example | Description |
/// |---------|---------|-------------|
/// | Direct body | `page!({ ... })` | Immediate `Page` with implicit `Clone` captures |
/// | No-arg factory | `page!(\|\| { ... })` | Callable factory with no params |
/// | Single parameter | `page!(\|name: String\| { ... })` | Callable factory with one prop |
/// | Multiple parameters | `page!(\|a: T1, b: T2\| { ... })` | Callable factory with multiple props |
/// | Signal parameter | `page!(\|sig: Signal<T>\| { ... })` | Callable factory with reactive signal prop |
///
/// ## HTML Elements
///
/// HTML elements are written as `tag { ... }`. The macro supports 70+ HTML elements
/// with compile-time validation.
///
/// ### Structural Elements
///
/// | Element | Description |
/// |---------|-------------|
/// | `div` | Generic container |
/// | `span` | Inline container |
/// | `p` | Paragraph |
/// | `header` | Header section |
/// | `footer` | Footer section |
/// | `main` | Main content |
/// | `nav` | Navigation |
/// | `section` | Generic section |
/// | `article` | Article content |
///
/// ### Headings
///
/// | Element | Description |
/// |---------|-------------|
/// | `h1` - `h6` | Heading levels 1-6 |
///
/// ### Text-Level Elements
///
/// | Element | Description |
/// |---------|-------------|
/// | `em`, `strong` | Emphasis, strong emphasis |
/// | `small`, `mark` | Small text, highlighted text |
/// | `b`, `i`, `u`, `s` | Bold, italic, underline, strikethrough |
/// | `code`, `kbd`, `samp`, `var` | Code, keyboard input, sample output, variable |
/// | `sub`, `sup` | Subscript, superscript |
/// | `br`, `wbr` | Line break, word break opportunity |
/// | `cite`, `abbr`, `time`, `dfn` | Citation, abbreviation, time, definition |
/// | `ins`, `del` | Inserted, deleted text |
/// | `q`, `blockquote` | Inline quote, block quote |
///
/// ### List Elements
///
/// | Element | Description |
/// |---------|-------------|
/// | `ul`, `ol` | Unordered list, ordered list |
/// | `li` | List item |
/// | `dl`, `dt`, `dd` | Definition list, term, description |
///
/// ### Table Elements
///
/// | Element | Description |
/// |---------|-------------|
/// | `table` | Table container |
/// | `thead`, `tbody`, `tfoot` | Table sections |
/// | `tr` | Table row |
/// | `th`, `td` | Header cell, data cell |
/// | `caption` | Table caption |
/// | `colgroup`, `col` | Column group, column |
///
/// ### Form Elements
///
/// | Element | Description |
/// |---------|-------------|
/// | `form` | Form container |
/// | `input` | Input field (void element) |
/// | `button` | Button |
/// | `label` | Form label |
/// | `select`, `option`, `optgroup` | Dropdown, option, option group |
/// | `textarea` | Multi-line text input |
///
/// ### Embedded Content
///
/// | Element | Description |
/// |---------|-------------|
/// | `img` | Image (requires `src` and `alt`) |
/// | `iframe` | Inline frame |
/// | `video`, `audio` | Video, audio player |
/// | `source`, `track` | Media source, text track |
/// | `canvas` | Drawing canvas |
/// | `picture` | Responsive image container |
/// | `script`, `noscript` | Script, fallback for no script |
/// | `object`, `param` | Embedded object, object parameters |
/// | `embed` | Embedded content |
///
/// ### Other Elements
///
/// | Element | Description |
/// |---------|-------------|
/// | `a` | Anchor/link |
/// | `hr` | Horizontal rule (void element) |
/// | `pre` | Preformatted text |
/// | `figure`, `figcaption` | Figure, figure caption |
/// | `details`, `summary` | Collapsible section |
/// | `dialog` | Dialog box |
/// | `data` | Machine-readable data value |
/// | `ruby`, `rt`, `rp` | Ruby annotations for East Asian typography |
/// | `bdi`, `bdo` | Bidirectional text isolation/override |
/// | `address` | Contact information |
/// | `template`, `slot` | HTML template, Web Components slot |
///
/// ### Void Elements
///
/// These elements cannot have children:
///
/// `br`, `col`, `embed`, `hr`, `img`, `input`, `param`, `source`, `track`, `wbr`
///
/// ## Attributes
///
/// Attributes use `key: value` syntax with automatic underscore-to-hyphen conversion.
///
/// ### Global Attributes
///
/// Available on all elements:
///
/// | Attribute | Description |
/// |-----------|-------------|
/// | `id` | Unique identifier |
/// | `class` | CSS class names |
/// | `style` | Inline CSS |
/// | `title` | Advisory title |
/// | `lang` | Language code |
/// | `dir` | Text direction (`ltr`, `rtl`) |
/// | `tabindex` | Tab order (integer) |
/// | `hidden` | Hidden state (boolean expression) |
/// | `role` | ARIA role |
/// | `data_*` | Custom data attributes (converted to `data-*`) |
/// | `aria_*` | Accessibility attributes (converted to `aria-*`) |
///
/// ### Attribute Value Types
///
/// | Type | Syntax | Example |
/// |------|--------|---------|
/// | String literal | `attr: "value"` | `class: "container"` |
/// | Expression | `attr: expr` | `class: css_class` |
/// | Integer literal | `attr: number` | `tabindex: 0` |
/// | Boolean expression | `attr: expr` | `disabled: is_disabled` |
///
/// ### Boolean Attributes
///
/// **Important**: Boolean attributes require expressions, not literals.
///
/// ```ignore
/// // CORRECT:
/// button { disabled: is_disabled }
/// input { checked: is_checked }
///
/// // INCORRECT (compile error):
/// button { disabled: true }      // ❌ Boolean literal not allowed
/// button { disabled: "disabled" } // ❌ String literal not allowed
/// ```
///
/// Boolean attributes: `disabled`, `required`, `readonly`, `checked`, `selected`,
/// `autofocus`, `autoplay`, `controls`, `loop`, `muted`, `default`, `defer`,
/// `formnovalidate`, `hidden`, `ismap`, `multiple`, `novalidate`, `open`, `reversed`
///
/// ### Numeric Attributes
///
/// Must be integer literals or expressions:
///
/// `size`, `min`, `max`, `step`, `rows`, `cols`, `colspan`, `rowspan`,
/// `tabindex`, `maxlength`, `minlength`
///
/// ### Enumerated Attributes
///
/// | Element | Attribute | Allowed Values |
/// |---------|-----------|----------------|
/// | `input` | `type` | `text`, `password`, `email`, `number`, `tel`, `url`, `search`, `checkbox`, `radio`, `submit`, `button`, `reset`, `file`, `hidden`, `date`, `datetime-local`, `time`, `week`, `month`, `color`, `range`, `image` |
/// | `button` | `type` | `submit`, `button`, `reset` |
/// | `form` | `method` | `get`, `post`, `dialog` |
/// | `form` | `enctype` | `application/x-www-form-urlencoded`, `multipart/form-data`, `text/plain` |
/// | `script` | `type` | `module`, `text/javascript`, `application/javascript` |
///
/// ### Example
///
/// ```ignore
/// page!(|| {
///     div {
///         class: "container",
///         id: "main",
///         data_testid: "test",  // Converts to data-testid
///         aria_label: "Main content",  // Converts to aria-label
///     }
/// })
/// ```
///
/// ## Event Handlers
///
/// Standard intrinsic events use `@event: handler` syntax. The authoritative
/// event catalog determines the accepted names and the distinct payload type
/// for each event. Unknown names are rejected with a nearby-name suggestion.
/// Arbitrary DOM events have explicit raw and typed forms:
/// `@custom("event-name"): handler` and
/// `@custom::<Detail>("event-name"): handler`.
/// Component `@event` props are separate: their argument type comes from the
/// component's declared prop and is not selected by the DOM event catalog.
///
/// ### Handler Syntax
///
/// ```ignore
/// use reinhardt_pages::event::{ClickEvent, InputEvent};
/// use reinhardt_pages::prelude::*;
/// use serde::Deserialize;
///
/// #[derive(Deserialize)]
/// struct ItemSelected {
///     id: u64,
/// }
///
/// // The payload is inferred from the standard event name.
/// button { @click: |event| { let _: ClickEvent = event; } }
///
/// // Explicit typed signatures use the same catalog-selected payload.
/// input { @input: |event: InputEvent| { let _ = event.value(); } }
///
/// // Zero-argument handlers remain supported.
/// button { @click: || { do_something(); } }
///
/// // Raw custom events retain the cross-target event transport.
/// div { @custom("item-selected"): |event: Event| { inspect(event); } }
///
/// // Typed custom events infer CustomEvent<ItemSelected> from the DSL.
/// div { @custom::<ItemSelected>("item-selected"): |event| {
///     if let Ok(detail) = event.detail() {
///         select(detail.id);
///     }
/// } }
/// ```
///
/// **Note**: Closures must have 0 or 1 parameter (compile error if more).
///
/// ## Child Nodes
///
/// ### Text Content
///
/// ```ignore
/// div { "Hello, World!" }
/// p { "Paragraph text" }
/// ```
///
/// ### Expressions
///
/// Every expression child must be wrapped in braces. Bare-identifier
/// shorthand was removed in Manouche v2 (spec §3.6); see the
/// `reinhardt-pages` CHANGELOG for the migration codemod.
///
/// ```ignore
/// div { {name} }                  // Variable
/// div { {name.to_string()} }      // Method call
/// div { {format!("{}", count)} }  // Macro
/// div { { complex_expr } }        // Block expression
/// ```
///
/// ### Nested Elements
///
/// ```ignore
/// div {
///     h1 { "Title" }
///     p { "Content" }
/// }
/// ```
///
/// ## Conditional Rendering
///
/// ### Basic if
///
/// ```ignore
/// div {
///     if condition {
///         span { "Visible when true" }
///     }
/// }
/// ```
///
/// ### if-else
///
/// ```ignore
/// div {
///     if condition {
///         span { "True branch" }
///     } else {
///         span { "False branch" }
///     }
/// }
/// ```
///
/// ### if-else if-else
///
/// ```ignore
/// div {
///     if count > 10 {
///         span { "Greater" }
///     } else if count == 10 {
///         span { "Equal" }
///     } else {
///         span { "Less" }
///     }
/// }
/// ```
///
/// ## List Rendering
///
/// ### Simple for Loop
///
/// ```ignore
/// ul {
///     for item in items {
///         li { {item} }
///     }
/// }
/// ```
///
/// ### With Destructuring
///
/// ```ignore
/// ul {
///     for (index, item) in items.iter().enumerate() {
///         li { { index.to_string() } ": " { item } }
///     }
/// }
/// ```
///
/// ### Nested Loops
///
/// ```ignore
/// div {
///     for row in matrix {
///         div {
///             for cell in row {
///                 span { { cell.to_string() } }
///             }
///         }
///     }
/// }
/// ```
///
/// ## Reactive Features
///
/// ### Auto-wrapped expressions and control flow
///
/// Expression, `if`, and `for` nodes are wrapped in `Page::reactive(move || ...)`.
/// Read signals inside those nodes when the rendered output should update as
/// the signals change:
///
/// ```ignore
/// page!({
///     div {
///         if error.get().is_some() {
///             div {
///                 class: "alert",
///                 { error.get().unwrap_or_default() }
///             }
///         }
///     }
/// })
/// ```
///
/// ### Reactive vs static values
///
/// | Scenario | Solution |
/// |----------|----------|
/// | Signal-dependent condition | Read the signal inside `if` |
/// | Signal-dependent list | Read the signal inside `for` |
/// | Static snapshot | Extract the value before calling `page!` |
///
/// ## Components
///
/// ### Component Calls
///
/// Call components with named arguments:
///
/// ```ignore
/// MyButton(label: "Click me")
///
/// MyCard(title: "Card", content: "Content", class: "custom")
/// ```
///
/// ### Component with Children
///
/// ```ignore
/// MyWrapper(class: "container") {
///     p { "Child content" }
///     span { "More content" }
/// }
/// ```
///
/// ## Head Directive (SSR)
///
/// For Server-Side Rendering, inject head content using `#head`:
///
/// ```ignore
/// page! {
///     #head: my_head,
///     || {
///         div { "Page content" }
///     }
/// }
/// ```
///
/// The head expression is called with `.with_head(head_expr)` on the resulting view.
///
/// ## Validation Rules
///
/// The macro performs compile-time validation:
///
/// ### Accessibility Requirements
///
/// | Element | Requirement |
/// |---------|-------------|
/// | `img` | Must have `src` (string literal) and `alt` attributes |
/// | `input`, `select`, `textarea` | Must have a non-empty `aria-label`, `aria-labelledby`, wrapping `label`, or matching `label for="id"` |
/// | `button`, `a` | Must have text content, `aria-label`, `aria-labelledby`, or an `img` child with non-empty `alt` |
/// | `iframe` | Must have a non-empty `title` |
///
/// Static `role` values must use a concrete WAI-ARIA 1.3 role. Static
/// `tabindex` values are limited to `0` and `-1` so generated markup does not
/// create positive keyboard tab order.
///
/// Add `a11y: off` to a specific element to opt out of accessibility checks for
/// that element when the markup intentionally relies on runtime behavior or
/// external labeling.
///
/// ### Security Validation
///
/// URL attributes block dangerous schemes to prevent XSS:
///
/// - ❌ `javascript:`
/// - ❌ `data:`
/// - ❌ `vbscript:`
///
/// Applies to: `href`, `src`, `action`, `formaction`
///
/// ### Element Nesting Rules
///
/// | Rule | Description |
/// |------|-------------|
/// | Void elements | Cannot have children (e.g., `img`, `input`, `br`) |
/// | Interactive elements | Cannot nest inside each other (`button`, `a`, `label`, `select`, `textarea`) |
/// | `select` | Can only contain `option` and `optgroup` |
/// | `ul`, `ol` | Can only contain `li` |
/// | `dl` | Can only contain `dt`, `dd`, and `div` |
///
/// ## Generated Code Structure
///
/// The direct `page!({ ... })` form generates a `Page` expression:
///
/// ```ignore
/// // page!({ div { class: "greeting", { name.clone() } } })
/// // Generates approximately:
/// {
///     let name = reinhardt_pages::__private::capture(&name);
///     PageElement::new("div")
///         .attr("class", "greeting")
///         .child(name.clone())
///         .into_page()
/// }
/// ```
///
/// Closure forms generate callable factories:
///
/// ```ignore
/// // page!(|name: String| { div { class: "greeting", { name } } })
/// // Generates approximately:
/// |name: String| -> Page {
///     PageElement::new("div")
///         .attr("class", "greeting")
///         .child(name)
///         .into_page()
/// }
/// ```
///
/// ### Event Handler Generation
///
/// ```ignore
/// // button { @click: |event| { handle(event) } }
/// // Generates on both native and WASM targets:
/// PageElement::new("button")
///     .on(
///         KnownEvent::Click,
///         typed_event_handler::<ClickEvent, _>(move |event| { handle(event) }),
///     )
/// ```
///
/// ## SSR/CSR Considerations
///
/// - **Event handlers**: Registered through the same raw storage path on WASM and native targets
/// - **head directive**: Enables SSR metadata injection
/// - **Same source code**: Works for both WASM and native targets
/// - **Native testing**: Registered handlers are available to the component harness
///
/// ## Complete Example
///
/// ```ignore
/// use reinhardt_pages::prelude::*;
///
/// fn todo_app(todos: Signal<Vec<String>>, filter: Signal<String>) -> View {
///     page!({
///         div {
///             class: "todo-app",
///
///             header {
///                 h1 { "My Todo App" }
///                 input {
///                     type: "text",
///                     placeholder: "Add a todo...",
///                     @input: |e| { /* handle input */ },
///                 }
///             }
///
///             nav {
///                 for filter_type in vec!["all", "active", "completed"] {
///                     button {
///                         @click: move |_| { /* set filter */ },
///                         { filter_type }
///                     }
///                 }
///             }
///
///             ul {
///                 class: "todo-list",
///                 if todos.get().is_empty() {
