///     script { src: "...", defer }
/// })
/// ```
///
/// ## Elements
///
/// ### Title
///
/// ```ignore
/// head!(|| {
///     title { "My Page Title" }
/// })
/// ```
///
/// ### Meta Tags
///
/// ```ignore
/// head!(|| {
