//! Procedural Macros for Reinhardt Pages
//!
//! This crate provides procedural macros for the reinhardt-pages WASM frontend framework.
//!
//! ## Available Macros
//!
//! - `page!` - Anonymous component DSL macro
//! - `head!` - HTML head section DSL macro
//! - `form!` - Type-safe form component macro with reactive bindings
//! - `#[server_fn]` - Server Functions (RPC) macro
//! - `#[server_fnset]` - Named server function set macro
//! - `#[client_page]` - Client page function macro with native route-table stubs
//! - `#[layout]` - Route-backed layout component macro for `ClientRouter`
//! - `#[loader]` - Async route-level data loader with hydration registration
//! - `#[wasm_server_api]` - API parity guard for matching WASM/server surfaces
//!
//! ## Form Design
//!
//! `form!` defines static form structure: field names, widgets, labels,
//! rendering metadata, and server function binding. Runtime behavior belongs to
//! `use_form`, whose runtime contract is generated by `form!`.
//!
//! `ambient_arguments` supplies server function arguments from surrounding
//! context rather than from user-facing fields. The old `strip_arguments` name
//! remains accepted as a deprecated alias. CSRF should be transported through
//! the `X-CSRFToken` header injected by `#[server_fn]` client stubs, not as a
//! server function business argument.
//!
//! ## page! Macro Example
//!
//! ```ignore
//! use reinhardt_pages::page;
//!
//! // Build a Page directly from surrounding Rust values.
//! let initial = 42;
//! let view = page!({
//!     div {
//!         class: "counter",
//!         h1 { "Counter" }
//!         span { { format!("Count: {}", initial) } }
//!     }
//! });
//!
//! // Define a reusable factory with closure-style props.
//! let counter = page!(|initial: i32| {
//!     div {
//!         class: "counter",
//!         h1 { "Counter" }
//!         span { { format!("Count: {}", initial) } }
//!         button {
//!             @click: |_| { /* handler */ },
//!             "+"
//!         }
//!     }
//! });
//!
//! let view = counter(42);
//! ```
//!
//! ## server_fn Example
//!
//! ```ignore
//! use reinhardt_pages_macros::server_fn;
//!
//! #[server_fn]
//! async fn get_user(id: u32) -> Result<User, ServerFnError> {
//!     // Server-side code (automatically removed on WASM build)
//!     let user = User::find_by_id(id).await?;
//!     Ok(user)
//! }
//!
//! // On client (WASM), this expands to an HTTP request
//! // On server, this expands to a route handler
//! ```

